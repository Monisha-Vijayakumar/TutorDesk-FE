import type { PaymentSearchParams, StudentPaymentSummary } from "./fee"

// A current (not deleted) student. Deleted students are soft-deleted by the BE and never returned.
export interface Student {
  id: string // internal UUID, used in URLs
  studentCode: string // login "Student ID", e.g. S100000001 — generated by the BE, never editable
  firstName: string
  lastName: string
  email: string | null
  phone: string // student's WhatsApp number; the parent's when the student has none of their own
  parentName: string
  parentPhone: string // parent's WhatsApp number
  grade: string
  subjects: string[]
  monthlyFee: number // paise
  joinDate: string // "YYYY-MM-DD"
  currentPayment: StudentPaymentSummary
  createdAt: string
}

// Query string for GET /students (search + payment filters + page), same as the Fees list.
export type StudentListParams = PaymentSearchParams

export interface StudentListResponse {
  students: Student[]
  total: number // matching students across all pages
}

// Fields the admin can set when adding or editing a student. Empty optional fields are sent as null.
export interface StudentDetailsPayload {
  firstName: string
  lastName: string
  email: string | null
  phone: string // already falls back to parentPhone when the form field is empty
  parentName: string
  parentPhone: string // parent's WhatsApp number
  grade: string
  subjects: string[]
  monthlyFee: number // paise
  joinDate: string
}

export interface CreateStudentPayload extends StudentDetailsPayload {
  password: string // initial password; the student must change it on first login
}

// Editing changes the same fields as adding, except the password.
export type UpdateStudentPayload = StudentDetailsPayload

export interface UpdateStudentRequest {
  studentId: string
  payload: UpdateStudentPayload
}

// Response of POST /students and PATCH /students/:id.
export interface StudentResponse {
  student: Student
}

// What every student service (real API or dev mock) must provide.
export interface StudentService {
  getStudents: (params: StudentListParams, signal?: AbortSignal) => Promise<StudentListResponse>
  createStudent: (payload: CreateStudentPayload) => Promise<Student>
  updateStudent: (studentId: string, payload: UpdateStudentPayload) => Promise<Student>
  deleteStudent: (studentId: string) => Promise<void>
}

// DEV mock storage only: the BE keeps deleted students in the DB with a deletedAt date (soft delete).
// currentPayment isn't stored: it's worked out from the mock fee records whenever a student is returned.
export interface MockStudentRecord extends Omit<Student, "currentPayment"> {
  deletedAt: string | null
}
